/**
 * The five runner alerts ship on every target (docker included: they read
 * application counters, nothing substrate-specific), say what they were
 * designed to say, and match only `code` values the pipeline service can
 * emit — a label value that is not in the catalog is an alert that never fires.
 */
describe('cross-account runner alerts', () => {
  const RUNNER_ALERTS = {
    // No hold: the gauge is debounced by the pings, and a broken runner stops
    // every pipeline in its account (one runner per account per org, no failover).
    RunnerUnreachable: { severity: 'warning', expr: 'max(pipeline_runners_unhealthy) > 0', for: '0m' },
    RunnerSigningKeyUnreadable: { severity: 'critical', expr: 'max(pipeline_runner_signing_keys_unreadable) > 0', for: '0m' },
    RunnerSignatureInvalid: { severity: 'critical', expr: 'sum(increase(pipeline_runner_delivery_total{code="SIGNATURE_INVALID"}[10m])) > 0', for: '0m' },
    RunnerRefusalSpike: { severity: 'warning', expr: 'pipeline_runner_delivery_total{outcome="refused", code=~"RUNNER_REFUSED|PIPELINE_IDENTITY_MISMATCH|AMBIGUOUS_PIPELINE"}[15m]', for: '5m' },
    RunnerRequestsExpiring: { severity: 'warning', expr: 'sum(increase(pipeline_runner_requests_total{status="expired"}[30m])) > 0', for: '0m' },
  } as const;
  const block = (rules: string, name: string) => {
    const start = rules.indexOf(`- alert: ${name}\n`);
    if (start < 0) return '';
    const next = rules.indexOf('- alert:', start + 10);
    return rules.slice(start, next < 0 ? undefined : next);
  };

  it.each(ALL_TARGETS)('%s carries all five, with their severity, window and hold', (target) => {
    const rules = read(`${target}/config/prometheus/alert-rules.yml`);
    for (const [name, spec] of Object.entries(RUNNER_ALERTS)) {
      const b = block(rules, name);
      expect([name, b.length > 0]).toEqual([name, true]);
      expect([name, b.includes(spec.expr)]).toEqual([name, true]);
      expect([name, b.includes(`severity: ${spec.severity}`)]).toEqual([name, true]);
      expect([name, b.includes(`for: ${spec.for}`)]).toEqual([name, true]);
      expect([name, b.includes('component: pipeline'), b.includes('tenancy: platform')]).toEqual([name, true, true]);
    }
  });

  it('matches only codes the catalog defines (error codes, delivery failure classes, none)', () => {
    const catalog = read('packages/api-core/src/types/pipeline-runners.ts');
    const classes = /RUNNER_DELIVERY_FAILURE_CLASSES = \[([^\]]+)\]/.exec(catalog)![1]!.match(/'([a-z0-9_]+)'/g)!.map((s) => s.slice(1, -1));
    const known = (c: string) => c === 'none' || classes.includes(c) || new RegExp(`^\\s+${c}: \\{`, 'm').test(catalog);
    const rules = read('deploy/local/minikube/config/prometheus/alert-rules.yml');
    const used = Object.keys(RUNNER_ALERTS).flatMap((n) => [...block(rules, n).matchAll(/code=~?"([^"]+)"/g)].flatMap((m) => m[1]!.split('|')));
    expect(used.length).toBeGreaterThan(3);
    for (const c of used) expect([c, known(c)]).toEqual([c, true]);
  });

  it('alerts on the unreadable-key gauge under the name the service exports', () => {
    expect(read('packages/api-core/src/types/pipeline-runners.ts')).toContain("'pipeline_runner_signing_keys_unreadable'");
  });

  it('has promtool cases for every runner alert, firing AND quiet', () => {
    const suite = read('deploy/local/minikube/config/prometheus/alert-rules.test.yml');
    for (const name of Object.keys(RUNNER_ALERTS)) {
      const cases = suite.split(/\n(?= {2}- interval:)/).filter((c) => c.includes(`alertname: ${name}\n`));
      expect([name, cases.some((c) => /exp_alerts:\n\s+- exp_labels/.test(c))]).toEqual([name, true]);
      expect([name, cases.some((c) => c.includes('exp_alerts: []'))]).toEqual([name, true]);
    }
  });
});

