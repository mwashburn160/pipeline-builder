/** Every text file under `rel`, skipping build output and dependencies. */
function walkFiles(rel: string, out: string[] = []): string[] {
  for (const entry of readdirSync(join(REPO_ROOT, rel))) {
    if (['node_modules', 'certs', 'coverage', 'lib', 'dist', 'test-reports'].includes(entry)) continue;
    const child = `${rel}/${entry}`;
    if (statSync(join(REPO_ROOT, child)).isDirectory()) walkFiles(child, out);
    else out.push(child);
  }
  return out;
}

describe('the shared runner signing key is gone', () => {
  // Built from parts so this file is not itself a hit.
  const SHARED = [
    ['runner-signing', 'keys.sh'].join('-'),
    ['RUNNER', 'SIGNING', 'KEY'].join('_'),
    ['pb_create', 'runner_signing', 'secret'].join('_'),
    ['runner-signing', 'key'].join('-') + '\n', // the k8s Secret name, as a manifest line end
    ['/api/pipelines/runner', 'jwks.json'].join('/'),
    ['cross_account', 'runners'].join('_'),
    ['/internal', 'features/'].join('/'),
  ];
  /**
   * Generated from the route tables and regenerated by the coordinator, never
   * edited by hand: it follows the code, not this suite.
   */
  const GENERATED = new Set(['docs/api-reference.md']);

  it('has no generator script', () => {
    expect(existsSync(join(REPO_ROOT, 'deploy/bin', SHARED[0]!))).toBe(false);
  });

  it('is named nowhere in deploy/ or docs/', () => {
    const hits: string[] = [];
    for (const f of [...walkFiles('deploy'), ...walkFiles('docs')]) {
      if (GENERATED.has(f) || f.startsWith('deploy/plugins/') || f.startsWith('deploy/samples/')) continue;
      const text = readFileSync(join(REPO_ROOT, f), 'utf-8');
      for (const needle of SHARED) if (text.includes(needle)) hits.push(`${f}: ${needle.trim()}`);
    }
    expect(hits).toEqual([]);
  });

  it.each(ALL_TARGETS)('%s: bring-up generates and mounts no runner key', (target) => {
    const setup = read(SETUP[target]);
    expect(setup).not.toContain('runner-signing');
    expect(read(`${target}/.env.example`)).not.toMatch(/^RUNNER_SIGNING/m);
  });

  it.each(K8S_TARGETS)('%s: the pipeline Deployment mounts no runner-signing Secret', (target) => {
    const deployment = yamlDocs<Doc>(`${target}/k8s/pipeline.yaml`).find((d) => d.kind === 'Deployment')!;
    const pod = deployment.spec.template.spec;
    expect(JSON.stringify(pod)).not.toContain('runner-signing');
  });

  it('the compose pipeline service has no runner-signing env or mount', () => {
    const services = yamlDocs<Doc>('deploy/local/docker/docker-compose.yml')[0]!.services as Record<string, Doc>;
    for (const [name, svc] of Object.entries(services)) {
      expect([name, JSON.stringify(svc ?? {}).includes('runner-signing')]).toEqual([name, false]);
    }
  });
});

