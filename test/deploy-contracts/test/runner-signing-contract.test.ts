/**
 * Pipeline runners — the deploy half.
 *
 * Runners are the only execution path, and every run request is signed with the
 * runner owner's PER-ORG Ed25519 key, kept in Postgres encrypted under the
 * per-org secret encryption. These assertions hold that:
 *   - the shared deployment key is gone: no generator script, no env setting, no
 *     mount, no Secret, no shared JWKS route anywhere in deploy/ or docs/;
 *   - the pipeline service gets what it needs to decrypt the keys on every
 *     target (SECRET_ENCRYPTION_KEY and the KMS settings, plus the KMS grants);
 *   - the platform holds no CodePipeline access on any target;
 *   - the mesh admits pipeline to platform's per-org KMS config and nothing
 *     else to it, and the retired org-features route has no rule left;
 *   - the runbook carries the per-org rotation, the re-encrypt job and the
 *     emergency stops;
 *   - the mesh admits pipeline to message's notify route (health notices).
 */

