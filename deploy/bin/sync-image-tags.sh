# Sync Docker image tags in deploy/ files to each service's package.json
# version. Run after a version bump (or in CI before publishing manifests).
#
# Source of truth: each service's package.json `version` field.
#
# Targets:
#   - deploy/local/minikube/k8s/*.yaml       (Kubernetes Deployment manifests)
#   - deploy/aws/ec2/k8s/*.yaml        (EC2 single-node k8s manifests)
#   - deploy/aws/eks/k8s/*.yaml        (EKS k8s manifests)
#   - deploy/local/docker/docker-compose.yml  (Docker Compose for local dev)
#   - deploy/aws/eks/.env.example  (EKS env defaults)
#   - deploy/toolchain/pipeline-bootstrap/Dockerfile  (pinned pipeline-manager version)
#   - the managed toolchain release (pipeline-bootstrap + cdk-synth specs):
#     sourceDigest, version and toolchain — see the end of this script
#
# Usage:
#   sync-image-tags.sh                    # everything (needs docker buildx + ghcr.io)
#   sync-image-tags.sh --toolchain-only   # only the bootstrap pin + toolchain release
#                                         # (offline; no registry access needed)
#
# Plugin image is a single target (no `-docker`/`-kaniko`/`-podman` suffix).
# Builds run on a rootless buildkitd sidecar across every deploy target.
#
# DIGEST PINNING. Every reference is written as `<svc>:<version>@sha256:<digest>`,
# and only AFTER that digest passed verify-image-signatures.sh (cosign keyless,
# identity = this repo's release.yml at refs/heads/main). A tag is mutable — a
# re-pushed or look-alike `:<version>` would otherwise be what the cluster pulls
# — while the digest is the exact artifact CI built, signed and scanned. The
# version stays in the ref for readers and for verify-image-tags.sh. Needs
# `docker buildx` (digest lookup) and network access to ghcr.io; the images must
# already be PUBLISHED — run this after the release workflow's publish job.
#
# VERSION LABELS MOVE WITH THE TAG. Every workload also declares its version as
# a pod label (`version:`), which mesh telemetry and the Prometheus
# `kubernetes-pods` scrape read. That is a SECOND place the version lives, so
# rewriting only the image ref here would leave the label behind — and
# test/deploy-contracts asserts label == image tag, so the next build would go
# red with a stale label rather than a missing one. Both are rewritten below,
# in one pass, from the same verified version.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
# common.sh for sha256_hash (the one portable SHA-256 the deploy scripts share).
SCRIPT_DIR="$ROOT/deploy/bin"
# shellcheck source=common.sh
. "$SCRIPT_DIR/common.sh"

TOOLCHAIN_ONLY=false
while [ $# -gt 0 ]; do
  case "$1" in
    --toolchain-only) TOOLCHAIN_ONLY=true; shift ;;
    --help|-h) sed -n '5,30p' "$0"; exit 0 ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done

# Image name → directory of its package.json (relative to repo root), for every
# image project in services.txt (generated by projen into every deploy target,
# byte-identical — test/deploy-contracts holds them equal). This script rewrites
# ALL FOUR targets in one pass rather than running for one of them, so it reads
# the docker target's copy, the same one the schema suites read.
SERVICES=()
while read -r _kind _name _dir; do
  case "$_kind" in service|frontend) SERVICES+=("${_name}:${_dir}") ;; esac
done < <(grep -v '^#' "$ROOT/deploy/local/docker/services.txt")

FILES=(
  "$ROOT"/deploy/local/minikube/k8s/*.yaml
  "$ROOT"/deploy/aws/ec2/k8s/*.yaml
  "$ROOT"/deploy/aws/eks/k8s/*.yaml
  "$ROOT/deploy/local/docker/docker-compose.yml"
  "$ROOT/deploy/aws/eks/.env.example"
)

# Cross-platform `sed -i` (BSD sed needs an explicit empty backup arg)
sed_i() {
  if sed --version >/dev/null 2>&1; then
    sed -E -i "$@"
  else
    sed -E -i '' "$@"
  fi
}

# Rewrite a service's `version:` pod label to $2 in file $3.
#
# $1 picks the shape: `single` for a per-service k8s manifest, which holds
# exactly one workload and so exactly one label; `compose` for
# docker-compose.yml, where every service shares one file and the label has to
# be found inside the right service block.
#
# Either way the edit goes to a temp file and is only moved into place when the
# label was found EXACTLY once. A sync that silently matched nothing would leave
# a stale version behind — which is the failure this function exists to stop, so
# it must abort the whole run rather than warn.
sync_version_label() {
  local _mode="$1" _svc="$2" _ver="$3" _file="$4" _tmp _rc=0
  [ -f "$_file" ] || return 0
  _tmp=$(mktemp)
  # `|| _rc=$?` keeps awk in a condition context. Without it `set -e` aborts the
  # whole script the moment awk signals "wrong number of labels", and the
  # diagnostic below — the only thing that says WHICH file and service — never
  # prints.
  if [ "$_mode" = compose ]; then
    awk -v svc="$_svc" -v ver="$_ver" '
      # service keys sit at exactly two spaces with nothing after the colon
      /^  [A-Za-z0-9_-]+:[[:space:]]*$/ { cur = $1; sub(/:$/, "", cur) }
      cur == svc && /^      version: "/ { sub(/version: ".*"/, "version: \"" ver "\""); n++ }
      { print }
      END { exit (n == 1 ? 0 : 1) }
    ' "$_file" > "$_tmp" || _rc=$?
  else
    # Keyed on the IMAGE, not the file name. `sync-image-tags.sh` rewrites refs
    # in EVERY deploy file, but an earlier version of this rewrote labels only in
    # `<svc>.yaml` — so `grype-db.yaml`, a CronJob that runs the plugin image,
    # took the new ref and kept the old label until the contract caught it. Any
    # workload running an owned image is covered now, wherever it lives.
    #
    # Documents are buffered and decided whole: the `version:` label sits in the
    # pod template ABOVE the `image:` line, so a streaming pass cannot know
    # whether to rewrite it until it has seen the rest of the document.
    # `index()` rather than a regex — the ref contains `.` and `/`, and the
    # trailing colon makes `<svc>:` exact (never matching `<svc>-other:`).
    awk -v img="ghcr.io/${OWNER}/${_svc}:" -v ver="$_ver" '
      function flush(   i, has, line) {
        has = 0
        for (i = 1; i <= n; i++) if (index(buf[i], img) > 0) has = 1
        for (i = 1; i <= n; i++) {
          line = buf[i]
          if (has && line ~ /^[[:space:]]+version: "/) {
            sub(/version: ".*"/, "version: \"" ver "\"", line)
            hits++
          }
          print line
        }
        n = 0
      }
      /^---$/ { flush(); print; next }
      { buf[++n] = $0 }
      END { flush(); exit (hits > 0 ? 0 : 2) }
    ' "$_file" > "$_tmp" || _rc=$?
    # 2 = this file simply holds no workload running that image, which is the
    # normal case for most files. Only a real awk failure is an error here; the
    # "it matched nothing ANYWHERE" check is made by the caller, across the tree.
    [ "$_rc" = 2 ] && { rm -f "$_tmp"; return 2; }
  fi
  if [ "$_rc" -ne 0 ]; then
    rm -f "$_tmp"
    echo "ERROR: could not rewrite the \`version:\` label for $_svc in $_file." >&2
    echo "       The label and the image tag would now disagree, which the deploy" >&2
    echo "       contract fails on. Fix the manifest and re-run." >&2
    return 1
  fi
  mv "$_tmp" "$_file"
  return 0
}

OWNER="${OWNER:-mwashburn160}"

[ "$TOOLCHAIN_ONLY" = true ] && SERVICES=()
for entry in "${SERVICES[@]+"${SERVICES[@]}"}"; do
  svc="${entry%%:*}"
  pkg="$ROOT/${entry##*:}/package.json"
  if [ ! -f "$pkg" ]; then
    echo "WARN: $pkg missing — skipping $svc"
    continue
  fi
  ver=$(node -p "require('$pkg').version" 2>/dev/null || jq -r .version "$pkg")
  if [ -z "$ver" ] || [ "$ver" = "null" ]; then
    echo "WARN: could not read version from $pkg — skipping $svc"
    continue
  fi

  # Resolve the published manifest-list digest, then verify ITS signature before
  # any file is touched. Either failing aborts the whole sync (set -e): a
  # half-pinned deploy tree is worse than an unchanged one.
  ref="ghcr.io/${OWNER}/${svc}:${ver}"
  # Capture stderr so a LOCAL auth failure isn't reported as a missing tag. GHCR
  # answers a request carrying an expired/revoked token with 403 rather than
  # falling back to anonymous, so a stale `docker login` makes a perfectly
  # published public image look absent.
  # `printf "%s"` is load-bearing: given a BARE field chain like
  # `{{ .Manifest.Digest }}`, buildx (seen on v0.27.0-desktop.1) ignores the
  # template and pretty-prints the whole manifest block, exiting 0. Wrapping the
  # field in any function takes the real template path and yields just the digest.
  inspect_err=$(mktemp)
  if ! digest=$(docker buildx imagetools inspect "$ref" --format '{{ printf "%s" .Manifest.Digest }}' 2>"$inspect_err"); then
    err=$(cat "$inspect_err"); rm -f "$inspect_err"
    echo "$err" >&2
    case "$err" in
      *"failed to authorize"*|*401*|*403*|*unauthorized*|*"denied:"*)
        echo "ERROR: registry REFUSED the request for $ref (auth), so it could not be" >&2
        echo "       checked. The images are public — a stale ghcr.io credential is the" >&2
        echo "       usual cause, because a bad token is rejected rather than ignored." >&2
        echo "       Fix: docker logout ghcr.io   (or re-login with a valid PAT)" >&2 ;;
      *"not found"*|*404*|*"manifest unknown"*|*MANIFEST_UNKNOWN*)
        echo "ERROR: $ref is not published — run this after the release workflow's" >&2
        echo "       publish job, or check the version in the service's package.json." >&2 ;;
      *)
        echo "ERROR: cannot resolve the digest of $ref (see the error above)." >&2 ;;
    esac
    exit 1
  fi
  rm -f "$inspect_err"
  # Never pin something that is not a digest. A multi-line block here means buildx
  # printed its manifest view instead of honoring --format (see above).
  case "$digest" in
    sha256:[0-9a-f]*)
      [ ${#digest} -eq 71 ] || { echo "ERROR: malformed digest for $ref: $digest" >&2; exit 1; } ;;
    *)
      echo "ERROR: did not get a digest for $ref. buildx returned:" >&2
      printf '%s\n' "$digest" | sed 's/^/       /' >&2
      echo "       This is buildx ignoring --format. Check the template in this script" >&2
      echo "       still wraps .Manifest.Digest in printf (buildx version: $(docker buildx version 2>/dev/null | awk '{print $2}'))." >&2
      exit 1 ;;
  esac
  PB_VERIFY_REFS="ghcr.io/${OWNER}/${svc}@${digest}" bash "$ROOT/deploy/bin/verify-image-signatures.sh" "$OWNER" >/dev/null \
    || { echo "ERROR: ${ref}@${digest} failed signature verification — not pinning it" >&2; exit 1; }
  echo "→ $svc: $ver@$digest (signature verified)"

  # Replace `ghcr.io/<owner>/<svc>:<anything>[@sha256:<old>]` with the verified
  # pin. `latest` and an old digest are rewritten too, so all targets converge.
  for f in "${FILES[@]}"; do
    [ -f "$f" ] || continue
    sed_i "s|(ghcr\\.io/${OWNER}/${svc}:)[A-Za-z0-9._]+(@sha256:[0-9a-f]{64})?|\\1${ver}@${digest}|g" "$f"
  done

  # The matching pod/service label. Only the files that actually carry one: the
  # three k8s trees name a manifest after its service, and compose keeps every
  # service in one file. `.env.example` holds refs but no labels.
  for tree in local/minikube aws/ec2 aws/eks; do
    # EVERY manifest in the tree, not just ${svc}.yaml — a workload running this
    # image can live in a file named after something else (grype-db.yaml runs the
    # plugin image). sync_version_label returns 2 for "no workload here", which is
    # the normal answer for most files; 1 is a real failure.
    _touched=0
    for _m in "$ROOT/deploy/$tree/k8s"/*.yaml; do
      [ -f "$_m" ] || continue
      if sync_version_label k8s "$svc" "$ver" "$_m"; then
        _touched=$((_touched + 1))
      else
        [ $? -eq 2 ] || exit 1
      fi
    done
    # Every owned service runs SOMEWHERE in every tree. Matching nothing means
    # the ref was re-pinned and no label moved with it — the exact drift this
    # function exists to prevent, so it must stop the release, not pass quietly.
    if [ "$_touched" -eq 0 ]; then
      echo "ERROR: $svc:$ver — no workload in deploy/$tree/k8s carries that image," >&2
      echo "       so no \`version:\` label was updated. Either the service is no" >&2
      echo "       longer deployed there, or its manifest lost the image ref." >&2
      exit 1
    fi
  done
  sync_version_label compose "$svc" "$ver" "$ROOT/deploy/local/docker/docker-compose.yml" || exit 1
done

# The pipeline-bootstrap image (deploy/toolchain/pipeline-bootstrap)
# bakes in the pipeline-manager CLI at a PINNED version. It is built per
# deployment by build-plugin-images.sh's base stage, not by the release, so
# nothing else moves that pin — keep it on the version this release just
# published to npm (the verify_release job runs this after verify-npm-deps.sh has
# proven it resolves). Exactly one ARG line must match, or the pin and the
# release would disagree with nothing saying so.
_bs_dir="$ROOT/deploy/toolchain/pipeline-bootstrap"
_synth_dir="$ROOT/deploy/toolchain/cdk-synth"
_bootstrap="$_bs_dir/Dockerfile"
_pm_pkg="$ROOT/packages/pipeline-manager/package.json"
for _f in "$_bootstrap" "$_bs_dir/plugin-spec.yaml" "$_synth_dir/Dockerfile" "$_synth_dir/plugin-spec.yaml" "$_pm_pkg"; do
  [ -f "$_f" ] || { echo "ERROR: $_f not found" >&2; exit 1; }
done
_pm_ver=$(node -p "require('$_pm_pkg').version" 2>/dev/null || jq -r .version "$_pm_pkg")
case "$_pm_ver" in
  [0-9]*.[0-9]*.[0-9]*) ;;
  *) echo "ERROR: could not read pipeline-manager's version from $_pm_pkg (got '$_pm_ver')" >&2; exit 1 ;;
esac
if [ "$(grep -cE '^ARG PIPELINE_MANAGER_VERSION=' "$_bootstrap")" -ne 1 ]; then
  echo "ERROR: expected exactly one 'ARG PIPELINE_MANAGER_VERSION=' line in $_bootstrap" >&2
  exit 1
fi
sed_i "s|^ARG PIPELINE_MANAGER_VERSION=.*$|ARG PIPELINE_MANAGER_VERSION=\"${_pm_ver}\"|" "$_bootstrap"
echo "→ pipeline-bootstrap: pipeline-manager ${_pm_ver}"

# ---- The managed toolchain release (pipeline-bootstrap + cdk-synth) ----------
#
# The two images are ONE release: both specs carry the same `version`, its own
# semver (pipeline-manager's version is recorded in `toolchain.pipelineManager`).
# `sourceDigest` is a hash of both directories' build inputs; when it changes,
# the patch of BOTH versions is bumped, so a pipeline-manager release, a Renovate
# `node:` digest bump or a cdk-synth Dockerfile edit each produce a new release.
# Minor/major bumps are made by hand, in both specs together.
#
# The hash EXCLUDES every generated field — the specs' `version`, `toolchain`,
# `sourceDigest` (and the human-written `changelog`), and cdk-synth's generated
# `ARG BOOTSTRAP_IMAGE=` default — so writing them never changes the hash and a
# re-run is a no-op. The writes are plain text edits of exactly those keys, never
# a YAML re-serialisation: a reformatted comment or re-quoted string elsewhere in
# a spec would change the hash on the next run and bump the version again.
#
# test/deploy-contracts (toolchain-drift-contract) recomputes this hash the same
# way and fails, naming this script, when the checked-in sourceDigest is stale.
# Keep the two in step: inputs = every top-level file in each directory except
# image.tar, plugin.zip, config.yaml (flipped by builds), README.md and
# .DS_Store; each framed as "<dir>/<file>\n" + its normalised lines.

# Print one input file's normalised content (every line newline-terminated).
_toolchain_normalise() {
  awk -v mode="$1" '
    mode == "spec" {
      if (skip) { if ($0 ~ /^[ \t]/ || $0 == "") next; skip = 0 }
      if ($0 ~ /^(version|toolchain|sourceDigest|changelog):/) { skip = 1; next }
    }
    mode == "synth-dockerfile" && /^ARG BOOTSTRAP_IMAGE=/ { print "ARG BOOTSTRAP_IMAGE=<generated>"; next }
    { print }
  ' "$2"
}

_toolchain_inputs() {
  local _d _f _mode
  for _d in "$_bs_dir" "$_synth_dir"; do
    while IFS= read -r _f; do
      case "$_f" in image.tar|plugin.zip|config.yaml|README.md|.DS_Store) continue ;; esac
      [ -f "$_d/$_f" ] || continue
      _mode=plain
      [ "$_f" = plugin-spec.yaml ] && _mode=spec
      [ "$_d" = "$_synth_dir" ] && [ "$_f" = Dockerfile ] && _mode=synth-dockerfile
      printf '%s/%s\n' "$(basename "$_d")" "$_f"
      _toolchain_normalise "$_mode" "$_d/$_f"
    done < <(ls -A "$_d" | LC_ALL=C sort)
  done
}

# One ARG value from the bootstrap Dockerfile (exactly one line, quoted or not).
_bs_arg() {
  local _v
  [ "$(grep -cE "^ARG $1=" "$_bootstrap")" -eq 1 ] \
    || { echo "ERROR: expected exactly one 'ARG $1=' line in $_bootstrap" >&2; return 1; }
  _v=$(sed -nE "s/^ARG $1=\"?([^\" ]+)\"?[[:space:]]*$/\1/p" "$_bootstrap")
  [ -n "$_v" ] || { echo "ERROR: could not read ARG $1 from $_bootstrap" >&2; return 1; }
  printf '%s' "$_v"
}

_tc_pm=$(_bs_arg PIPELINE_MANAGER_VERSION)
_tc_cdk=$(_bs_arg AWS_CDK_VERSION)
_tc_assets=$(_bs_arg CDK_ASSETS_VERSION)
_tc_esbuild=$(_bs_arg ESBUILD_VERSION)
_tc_pnpm=$(_bs_arg PNPM_VERSION)
# Node is the base image's version: the tag of the digest-pinned NODE_IMAGE.
_tc_node=$(sed -nE 's/^ARG NODE_IMAGE=node:([0-9]+\.[0-9]+\.[0-9]+)-.*/\1/p' "$_bootstrap")
[ -n "$_tc_node" ] || { echo "ERROR: could not read the node version from ARG NODE_IMAGE in $_bootstrap" >&2; exit 1; }

_src_digest="sha256:$(_toolchain_inputs | sha256_hash)"

# Both specs must hold exactly one `version:` line, a plain X.Y.Z.
_spec_version() {
  local _v
  [ "$(grep -cE '^version:' "$1")" -eq 1 ] || { echo "ERROR: expected exactly one 'version:' line in $1" >&2; return 1; }
  _v=$(get_spec_field version "$1" | tr -d "\"'")
  case "$_v" in
    [0-9]*.[0-9]*.[0-9]*) printf '%s' "$_v" ;;
    *) echo "ERROR: $1 version '$_v' is not X.Y.Z" >&2; return 1 ;;
  esac
}
_v_bs=$(_spec_version "$_bs_dir/plugin-spec.yaml")
_v_synth=$(_spec_version "$_synth_dir/plugin-spec.yaml")
# The release is the higher of the two (a hand bump made in only one spec is
# carried to the other, never lost).
_release=$(printf '%s\n%s\n' "$_v_bs" "$_v_synth" | LC_ALL=C sort -t. -k1,1n -k2,2n -k3,3n | tail -1)
_recorded=$(get_spec_field sourceDigest "$_bs_dir/plugin-spec.yaml" | tr -d "\"'")
# No recorded digest = a spec that has never been synced: record the digest at
# the version it already names instead of bumping past it.
if [ -n "$_recorded" ] && [ "$_recorded" != "$_src_digest" ]; then
  _major=${_release%%.*}; _rest=${_release#*.}; _minor=${_rest%%.*}; _patch=${_rest#*.}
  _release="${_major}.${_minor}.$((_patch + 1))"
  echo "→ toolchain: build inputs changed — release bumped to ${_release}"
fi

# Rewrite exactly the generated keys. version in place; toolchain + sourceDigest
# removed wherever they are and re-appended at the end, so the output depends
# only on the values (deterministic, and a re-run reproduces it byte for byte).
sed_i "s|^version:.*$|version: ${_release}|" "$_bs_dir/plugin-spec.yaml" "$_synth_dir/plugin-spec.yaml"
_spec_tmp=$(mktemp)
awk '
  skip { if ($0 ~ /^[ \t]/ || $0 == "") next; skip = 0 }
  /^(toolchain|sourceDigest):/ { skip = 1; next }
  { print }
' "$_bs_dir/plugin-spec.yaml" > "$_spec_tmp"
{
  cat "$_spec_tmp"
  printf 'toolchain:\n'
  printf '  pipelineManager: "%s"\n' "$_tc_pm"
  printf '  awsCdk: "%s"\n' "$_tc_cdk"
  printf '  cdkAssets: "%s"\n' "$_tc_assets"
  printf '  esbuild: "%s"\n' "$_tc_esbuild"
  printf '  pnpm: "%s"\n' "$_tc_pnpm"
  printf '  node: "%s"\n' "$_tc_node"
  printf 'sourceDigest: "%s"\n' "$_src_digest"
} > "$_bs_dir/plugin-spec.yaml"
rm -f "$_spec_tmp"
# cdk-synth's out-of-script default base: the same release, by its version tag.
[ "$(grep -cE '^ARG BOOTSTRAP_IMAGE=' "$_synth_dir/Dockerfile")" -eq 1 ] \
  || { echo "ERROR: expected exactly one 'ARG BOOTSTRAP_IMAGE=' line in $_synth_dir/Dockerfile" >&2; exit 1; }
sed_i "s|^ARG BOOTSTRAP_IMAGE=.*$|ARG BOOTSTRAP_IMAGE=\"pipeline-bootstrap:${_release}\"|" "$_synth_dir/Dockerfile"
echo "→ toolchain release ${_release}: pipeline-manager ${_tc_pm}, aws-cdk ${_tc_cdk}, cdk-assets ${_tc_assets}, node ${_tc_node} (${_src_digest})"

echo "Done. Review the diff with: git diff -- deploy/"
