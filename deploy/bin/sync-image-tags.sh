# Sync Docker image tags in deploy/ files to each service's package.json
# version. Run after a version bump (or in CI before publishing manifests).
#
# Source of truth: each service's package.json `version` field.
#
# Targets:
#   - deploy/local/minikube/k8s/*.yaml       (Kubernetes Deployment manifests)
#   - deploy/aws/ec2/k8s/*.yaml        (EC2 single-node k8s manifests)
#   - deploy/aws/eks/k8s/*.yaml        (EKS k8s manifests)
#   - deploy/local/docker/docker-compose.yml  (Docker Compose for local dev)
#   - deploy/aws/eks/.env.example  (EKS env defaults)
#
# Plugin image is a single target (no `-docker`/`-kaniko`/`-podman` suffix).
# Builds run on a rootless buildkitd sidecar across every deploy target.
#
# DIGEST PINNING. Every reference is written as `<svc>:<version>@sha256:<digest>`,
# and only AFTER that digest passed verify-image-signatures.sh (cosign keyless,
# identity = this repo's release.yml at refs/heads/main). A tag is mutable — a
# re-pushed or look-alike `:<version>` would otherwise be what the cluster pulls
# — while the digest is the exact artifact CI built, signed and scanned. The
# version stays in the ref for readers and for verify-image-tags.sh. Needs
# `docker buildx` (digest lookup) and network access to ghcr.io; the images must
# already be PUBLISHED — run this after the release workflow's publish job.

set -euo pipefail

ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"

# Image name → directory of its package.json (relative to repo root), for every
# image project in services.txt (generated by projen into every deploy target,
# byte-identical — test/deploy-contracts holds them equal). This script rewrites
# ALL FOUR targets in one pass rather than running for one of them, so it reads
# the docker target's copy, the same one the schema suites read.
SERVICES=()
while read -r _kind _name _dir; do
  case "$_kind" in service|frontend) SERVICES+=("${_name}:${_dir}") ;; esac
done < <(grep -v '^#' "$ROOT/deploy/local/docker/services.txt")

FILES=(
  "$ROOT"/deploy/local/minikube/k8s/*.yaml
  "$ROOT"/deploy/aws/ec2/k8s/*.yaml
  "$ROOT"/deploy/aws/eks/k8s/*.yaml
  "$ROOT/deploy/local/docker/docker-compose.yml"
  "$ROOT/deploy/aws/eks/.env.example"
)

# Cross-platform `sed -i` (BSD sed needs an explicit empty backup arg)
sed_i() {
  if sed --version >/dev/null 2>&1; then
    sed -E -i "$@"
  else
    sed -E -i '' "$@"
  fi
}

OWNER="${OWNER:-mwashburn160}"

for entry in "${SERVICES[@]}"; do
  svc="${entry%%:*}"
  pkg="$ROOT/${entry##*:}/package.json"
  if [ ! -f "$pkg" ]; then
    echo "WARN: $pkg missing — skipping $svc"
    continue
  fi
  ver=$(node -p "require('$pkg').version" 2>/dev/null || jq -r .version "$pkg")
  if [ -z "$ver" ] || [ "$ver" = "null" ]; then
    echo "WARN: could not read version from $pkg — skipping $svc"
    continue
  fi

  # Resolve the published manifest-list digest, then verify ITS signature before
  # any file is touched. Either failing aborts the whole sync (set -e): a
  # half-pinned deploy tree is worse than an unchanged one.
  ref="ghcr.io/${OWNER}/${svc}:${ver}"
  # Capture stderr so a LOCAL auth failure isn't reported as a missing tag. GHCR
  # answers a request carrying an expired/revoked token with 403 rather than
  # falling back to anonymous, so a stale `docker login` makes a perfectly
  # published public image look absent.
  # `printf "%s"` is load-bearing: given a BARE field chain like
  # `{{ .Manifest.Digest }}`, buildx (seen on v0.27.0-desktop.1) ignores the
  # template and pretty-prints the whole manifest block, exiting 0. Wrapping the
  # field in any function takes the real template path and yields just the digest.
  inspect_err=$(mktemp)
  if ! digest=$(docker buildx imagetools inspect "$ref" --format '{{ printf "%s" .Manifest.Digest }}' 2>"$inspect_err"); then
    err=$(cat "$inspect_err"); rm -f "$inspect_err"
    echo "$err" >&2
    case "$err" in
      *"failed to authorize"*|*401*|*403*|*unauthorized*|*"denied:"*)
        echo "ERROR: registry REFUSED the request for $ref (auth), so it could not be" >&2
        echo "       checked. The images are public — a stale ghcr.io credential is the" >&2
        echo "       usual cause, because a bad token is rejected rather than ignored." >&2
        echo "       Fix: docker logout ghcr.io   (or re-login with a valid PAT)" >&2 ;;
      *"not found"*|*404*|*"manifest unknown"*|*MANIFEST_UNKNOWN*)
        echo "ERROR: $ref is not published — run this after the release workflow's" >&2
        echo "       publish job, or check the version in the service's package.json." >&2 ;;
      *)
        echo "ERROR: cannot resolve the digest of $ref (see the error above)." >&2 ;;
    esac
    exit 1
  fi
  rm -f "$inspect_err"
  # Never pin something that is not a digest. A multi-line block here means buildx
  # printed its manifest view instead of honoring --format (see above).
  case "$digest" in
    sha256:[0-9a-f]*)
      [ ${#digest} -eq 71 ] || { echo "ERROR: malformed digest for $ref: $digest" >&2; exit 1; } ;;
    *)
      echo "ERROR: did not get a digest for $ref. buildx returned:" >&2
      printf '%s\n' "$digest" | sed 's/^/       /' >&2
      echo "       This is buildx ignoring --format. Check the template in this script" >&2
      echo "       still wraps .Manifest.Digest in printf (buildx version: $(docker buildx version 2>/dev/null | awk '{print $2}'))." >&2
      exit 1 ;;
  esac
  PB_VERIFY_REFS="ghcr.io/${OWNER}/${svc}@${digest}" bash "$ROOT/deploy/bin/verify-image-signatures.sh" "$OWNER" >/dev/null \
    || { echo "ERROR: ${ref}@${digest} failed signature verification — not pinning it" >&2; exit 1; }
  echo "→ $svc: $ver@$digest (signature verified)"

  # Replace `ghcr.io/<owner>/<svc>:<anything>[@sha256:<old>]` with the verified
  # pin. `latest` and an old digest are rewritten too, so all targets converge.
  for f in "${FILES[@]}"; do
    [ -f "$f" ] || continue
    sed_i "s|(ghcr\\.io/${OWNER}/${svc}:)[A-Za-z0-9._]+(@sha256:[0-9a-f]{64})?|\\1${ver}@${digest}|g" "$f"
  done
done

echo "Done. Review the diff with: git diff -- deploy/"
