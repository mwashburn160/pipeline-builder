#!/usr/bin/env bash
set -euo pipefail

# Build Docker images for plugins, save as image.tar, and update config.yaml.
#
# For each plugin: docker build → docker save → image.tar → update config.yaml
# The image.tar is gitignored and bundled into plugin.zip by load-plugins.sh.
#
# Usage:
#   ./build-plugin-images.sh                    # build all (prompt to recreate existing)
#   ./build-plugin-images.sh --force            # rebuild all, no prompt
#   ./build-plugin-images.sh --category language # build one category
#   ./build-plugin-images.sh --reset            # revert all to build_image
#
# NOTE: docker save captures single-platform images only. For multi-platform
# (ARM/x86), use docker buildx with --platform and save each platform
# separately. This is not implemented — documented as a limitation.

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
. "$SCRIPT_DIR/common.sh"
PLUGINS_DIR="$DEPLOY_DIR/plugins"
FORCE=false
RESET=false
DRY_RUN=false
BASES_ONLY=false
# When true, trust that the base images are ALREADY in the in-cluster registry and
# skip building+pushing them. Required on hosts with no Docker daemon (e.g. a
# Docker-less host or CI runner): the bases are prebuilt in CI and seeded into
# the registry out-of-band.
# Default false — local/minikube/ec2 build the bases as before.
BASES_PREBUILT="${BASES_PREBUILT:-false}"
CATEGORY_FILTER=""
MAX_IMAGE_SIZE_MB="${MAX_IMAGE_SIZE_MB:-4096}"

# Platform all plugin/base images are built for. An explicit PUBLISH_PLATFORM
# always wins. Otherwise the default depends on where the images RUN:
#   - local targets (docker/minikube) run them on THIS host, so build for the
#     host arch. Defaulting to linux/amd64 there forces QEMU emulation on an
#     Apple-Silicon host, where the Rust toolchain SIGSEGVs building rust-base
#     (`qemu: uncaught target signal 11`).
#   - AWS / unknown targets keep linux/amd64 — the CodeBuild x86 runtime. Push a
#     linux/arm64 build only for an all-Graviton stack (set PUBLISH_PLATFORM).
# (On an amd64 host the local branch also resolves to linux/amd64 = native.)
if [ -z "${PUBLISH_PLATFORM:-}" ]; then
  case "${DEPLOY_TARGET:-}" in
    docker|minikube)
      case "$(uname -m)" in
        arm64|aarch64) PUBLISH_PLATFORM="linux/arm64" ;;
        *)             PUBLISH_PLATFORM="linux/amd64" ;;
      esac
      ;;
    *) PUBLISH_PLATFORM="linux/amd64" ;;
  esac
fi

# Base-image builder. "docker" (default) = `docker build` (needs a Docker daemon, the
# local/minikube/ec2 path). "buildkit" = build via `buildctl` against BUILDKIT_HOST and
# push straight to the registry — NO Docker daemon (a Docker-less host with a buildkitd
# sidecar). In buildkit mode push-base-images.sh is skipped (buildctl pushes directly).
BASE_BUILDER="${BASE_BUILDER:-docker}"
# In-cluster registry the buildkit builder pushes bases to (must match the buildkitd
# mirror, e.g. registry:5000 on the k8s targets).
REGISTRY_HOST="${REGISTRY_HOST:-registry:5000}"
# The deploy's OWN internal-token signing key + the public bundle, used to
# authenticate the buildkit push against the in-cluster registry. Generated by
# deploy/bin/service-signing-keys.sh into the TARGET's certs dir (the same place
# its setup.sh puts the TLS and user-token-signing material), so resolve that
# rather than assuming a single layout. Overridable for an out-of-tree deploy.
case "${DEPLOY_TARGET:-docker}" in
  minikube) _pb_target_dir="$DEPLOY_DIR/local/minikube" ;;
  ec2)      _pb_target_dir="$DEPLOY_DIR/aws/ec2" ;;
  eks)      _pb_target_dir="$DEPLOY_DIR/aws/eks" ;;
  *)        _pb_target_dir="$DEPLOY_DIR/local/docker" ;;
esac
BOOTSTRAP_KEY_FILE="${BOOTSTRAP_KEY_FILE:-$_pb_target_dir/certs/service-keys/deploy-bootstrap.key}"
BOOTSTRAP_BUNDLE_FILE="${BOOTSTRAP_BUNDLE_FILE:-$_pb_target_dir/certs/service-keys/bundle.json}"
REGISTRY_INSECURE="${REGISTRY_INSECURE:-true}"
BUILDKIT_HOST="${BUILDKIT_HOST:-}"

# ---- Argument parsing ----
#
# Remembered before the loop consumes them, for the "re-run this command" hint
# in the docker-daemon error below.
_ORIG_ARGS="$*"
#
# The deploy/bin convention (as in backup.sh / restore.sh / load-plugins.sh): a
# value-taking flag asserts its value is THERE before reading it. A bare `"$2"`
# on a trailing flag dies under `set -u` with `$2: unbound variable`, naming
# neither flag nor script.

while [ $# -gt 0 ]; do
  case "$1" in
    --force|--rebuild) FORCE=true; shift ;;
    --reset)     RESET=true; shift ;;
    --dry-run)   DRY_RUN=true; shift ;;
    --bases-only) BASES_ONLY=true; shift ;;
    --skip-bases) BASES_PREBUILT=true; shift ;;
    # Accumulate across repeated flags AND accept a comma-separated value, so
    # both `--category a,b` and `--category a --category b` build a+b — matching
    # load-plugins.sh, which is handed the same `--category` argument by
    # init-platform.sh. Plain assignment silently kept only the LAST flag.
    --category)  [ $# -ge 2 ] || { echo "ERROR: $1 requires a value" >&2; exit 1; }
                 CATEGORY_FILTER="${CATEGORY_FILTER:+$CATEGORY_FILTER,}$2"; shift 2 ;;
    --max-image-size) [ $# -ge 2 ] || { echo "ERROR: $1 requires a value" >&2; exit 1; }
                 MAX_IMAGE_SIZE_MB="$2"
                 [[ "$MAX_IMAGE_SIZE_MB" =~ ^[1-9][0-9]*$ ]] || { echo "ERROR: --max-image-size requires a positive integer" >&2; exit 1; }
                 shift 2 ;;
    --help|-h)
      echo "Usage: $0 [options]"
      echo ""
      echo "Options:"
      echo "  --force              Rebuild all images, no prompt for existing"
      echo "  --reset              Revert all plugins to buildType: build_image"
      echo "  --dry-run            Show what would be built without building"
      echo "  --bases-only         Build + push base images only, skip per-plugin builds"
      echo "  --skip-bases         Trust prebuilt bases already in the registry; skip the base"
      echo "                       docker build+push (also: BASES_PREBUILT=true). For hosts with"
      echo "                       no Docker daemon (e.g. a CI runner) where bases are seeded out-of-band."
      echo "  --category CATS      Comma-separated categories (e.g., language,security)"
      echo "  --max-image-size MB  Skip images larger than MB (default: 4096)"
      exit 0
      ;;
    *) echo "Unknown option: $1" >&2; exit 1 ;;
  esac
done

# Tool checks AFTER argument parsing, so `--help` answers on any host — a
# daemon-less box asking what the flags are should get the flags, not an error
# about docker.
require_yq

# Fail fast with a useful message when the current user can't reach the
# docker socket. Common case on EC2: the user is `ec2-user` who hasn't been
# added to the docker group (bootstrap.sh adds them, but the user must
# re-login or run `newgrp docker` for it to take effect).
if ! docker info >/dev/null 2>&1; then
  echo "ERROR: cannot reach docker daemon (permission denied or daemon down)" >&2
  echo "  Current user: $(id -un)" >&2
  echo "  Fix: ensure your user is in the 'docker' group, then re-login or run:" >&2
  echo "    newgrp docker && bash $0 ${_ORIG_ARGS}" >&2
  echo "  Or run this script with sudo." >&2
  exit 1
fi

# ---- Build base images FIRST (dependency order) ----
#
# All base images live under `_base/` (the loop auto-detects every `_*-base`):
#   _base/_plugin-base/    → pipeline-plugin-base:24.04 (root, built first)
#   _base/_{python,node,go,jvm,dotnet,rust,ruby,php}-base/
#                          → pipeline-<eco>-base:1.0 (one pinned runtime each,
#                            consumed by every plugin in that ecosystem)
#   _base/_trivy-base/     → pipeline-trivy-base:1.0 (language-agnostic trivy)
#   _base/_aws-cli-base/   → pipeline-aws-cli-base:1.0
#
# `_plugin-base` is built before any family base (family bases inherit FROM
# the root). Family bases are built alphabetically — they don't depend on
# each other.
#
# All `_*` directories at any depth are infrastructure, not plugins —
# excluded from the upload/load flow by the `! -name '_*'` filter on
# category list at the top level.
# Detect EC2 region (if running on EC2) and pick a regional Ubuntu mirror.
# Same-region traffic stays in AWS (free + fast — 100s of MB/s vs the ~1
# MB/s archive.ubuntu.com gives EC2 boxes). On non-EC2 hosts (or when IMDS
# is disabled), prints nothing and apt uses the global mirror as before.
#
# Operator override: `APT_MIRROR=<host>` env var bypasses detection.
_detect_apt_mirror() {
  if [ -n "${APT_MIRROR:-}" ]; then
    echo "$APT_MIRROR"
    return
  fi
  # Explicit init — bash 3.2 (macOS default) treats unassigned `local`
  # vars as unbound under `set -u`, so a non-EC2 host (empty _token,
  # _region never assigned) trips line 104. Initialize both to "".
  local _token="" _region=""
  # IMDSv2 token first (required on hardened EC2). Tiny timeout so we don't
  # stall non-EC2 builds.
  _token=$(curl -sf -X PUT --max-time 1 \
    -H "X-aws-ec2-metadata-token-ttl-seconds: 60" \
    http://169.254.169.254/latest/api/token 2>/dev/null || true)
  if [ -n "$_token" ]; then
    _region=$(curl -sf --max-time 1 \
      -H "X-aws-ec2-metadata-token: $_token" \
      http://169.254.169.254/latest/meta-data/placement/region 2>/dev/null || true)
  fi
  [ -n "$_region" ] && echo "${_region}.ec2.archive.ubuntu.com"
}

# _is_transient_failure — true when a docker-build log matches a known
# transient apt/network mirror flap. Anything else is a real bug and
# should fail immediately so the operator sees it. The pattern list is
# the historical accumulation of mirror failure shapes we've observed
# (archive.ubuntu.com, launchpad, sury, npm registry, gradle plugin
# portal, etc.) — extend here, not at the call site, when a new flap
# shape shows up.
_TRANSIENT_PATTERNS='connection timed out'
_TRANSIENT_PATTERNS+='|Could not connect'
_TRANSIENT_PATTERNS+='|Temporary failure resolving'
_TRANSIENT_PATTERNS+='|503 Service Unavailable'
_TRANSIENT_PATTERNS+='|504 Gateway'
_TRANSIENT_PATTERNS+='|Gateway Time-out'
_TRANSIENT_PATTERNS+='|Connection reset by peer'
_TRANSIENT_PATTERNS+='|TLS handshake'
_TRANSIENT_PATTERNS+='|Connection failed'
_TRANSIENT_PATTERNS+='|Failed to fetch'
_TRANSIENT_PATTERNS+='|Unable to fetch some archives'
_TRANSIENT_PATTERNS+='|did not get expected size'
_TRANSIENT_PATTERNS+='|hash sum mismatch'
_TRANSIENT_PATTERNS+="|server can't find"
_TRANSIENT_PATTERNS+='|HTTP 5[0-9]{2}'
_TRANSIENT_PATTERNS+='|EOF occurred in violation of protocol'
_TRANSIENT_PATTERNS+='|read timeout'
_TRANSIENT_PATTERNS+='|operation timed out'
_TRANSIENT_PATTERNS+='|Network is unreachable'
_TRANSIENT_PATTERNS+='|No route to host'
_is_transient_failure() {
  grep -qE "$_TRANSIENT_PATTERNS" "$1"
}

# Build a single base image with output captured. Silent on success
# (just prints "  ✓ tag (Ns)"); dumps last 30 lines on failure. Set
# VERBOSE_BUILD=1 to stream output the old way (debugging).
_build_base_quiet() {
  local _tag="$1" _ctx="$2"
  local _start _elapsed _log _rc=0
  local _build_extra=""
  # Only the root base image takes APT_MIRROR as a build arg. Family bases
  # (cpp/rust/jvm/…) DO apt-install, but they build FROM plugin-base and inherit
  # its already-rewritten apt sources, so they hit the same mirror without
  # needing the arg re-passed.
  if [ "$(basename "$_ctx")" = "_plugin-base" ]; then
    local _mirror
    _mirror=$(_detect_apt_mirror)
    [ -n "$_mirror" ] && _build_extra="--build-arg APT_MIRROR=${_mirror}"
    [ -n "$_mirror" ] && echo "  → using apt mirror: ${_mirror}"
  fi
  # --force ⇒ drop the Docker layer cache so a rebuild actually re-runs (apt
  # installs, COPY --from, tool installs) instead of replaying cached layers.
  # Without this an unchanged Dockerfile "builds" in 0s and --force is a silent
  # no-op for base images.
  [ "$FORCE" = true ] && _build_extra="$_build_extra --no-cache"
  _start=$(date +%s)
  if [ "${VERBOSE_BUILD:-0}" = "1" ]; then
    # shellcheck disable=SC2086
    docker build --progress plain --platform "$PUBLISH_PLATFORM" $_build_extra -t "$_tag" "$_ctx" || _rc=$?
  else
    _log=$(mktemp)
    # shellcheck disable=SC2086
    docker build --progress plain --platform "$PUBLISH_PLATFORM" $_build_extra -t "$_tag" "$_ctx" > "$_log" 2>&1 || _rc=$?
    if [ "$_rc" -ne 0 ]; then
      echo "  ✗ $_tag — build failed (last 30 lines):" >&2
      tail -30 "$_log" | sed 's/^/    /' >&2
    fi
    rm -f "$_log"
  fi
  _elapsed=$(($(date +%s) - _start))
  [ "$_rc" -eq 0 ] && echo "  ✓ $_tag (${_elapsed}s)"
  return "$_rc"
}

# Write a one-time docker config with the in-cluster registry's `_token` credential so
# buildctl can PUSH the built base. Mirrors how api/plugin drives buildkitd (DOCKER_CONFIG
# carries the registry auth the buildkit exporter reads). The JWT is the deploy's own
# ES256 `deploy-bootstrap` service token — there is no shared secret to sign with.
_BK_AUTH_DIR=""
_setup_buildkit_auth() {
  [ -n "$_BK_AUTH_DIR" ] && return 0
  local _jwt _auth
  _jwt="$(sign_service_jwt "${BOOTSTRAP_KEY_FILE:?BOOTSTRAP_KEY_FILE must be set}" "${BOOTSTRAP_BUNDLE_FILE:?BOOTSTRAP_BUNDLE_FILE must be set}")"
  [ -z "$_jwt" ] && { echo "ERROR: failed to sign the deploy-bootstrap service token for the buildkit push" >&2; return 1; }
  _auth="$(printf '%s' "_token:${_jwt}" | base64 | tr -d '\n')"
  _BK_AUTH_DIR="$(mktemp -d)"
  ( umask 077; cat > "$_BK_AUTH_DIR/config.json" <<JSON
{ "auths": { "${REGISTRY_HOST}": { "auth": "${_auth}" } } }
JSON
  )
}

# Build one base via buildctl (no Docker) and push it to ${REGISTRY_HOST}/library/<tag>.
_build_base_buildkit() {
  local _tag="$1" _ctx="$2" _rc=0
  _setup_buildkit_auth || return 1
  [ -z "$BUILDKIT_HOST" ] && { echo "  ✗ $_tag — BUILDKIT_HOST is empty (no buildkitd to build against)" >&2; return 1; }
  local _out="type=image,name=${REGISTRY_HOST}/library/${_tag},push=true"
  [ "$REGISTRY_INSECURE" = "true" ] && _out="${_out},registry.insecure=true"
  # The root base takes APT_MIRROR; family bases inherit a fully-installed base (no apt).
  local _opt_args=()
  if [ "$(basename "$_ctx")" = "_plugin-base" ]; then
    local _mirror; _mirror=$(_detect_apt_mirror)
    [ -n "$_mirror" ] && _opt_args+=(--opt "build-arg:APT_MIRROR=${_mirror}")
  fi
  # --force ⇒ bust buildkit's cache so the rebuild actually re-runs (parity
  # with the docker path). buildkit pushes directly (push=true), so there's
  # no separate FORCE_PUSH step here — --no-cache is the whole story.
  [ "$FORCE" = true ] && _opt_args+=(--no-cache)
  local _start; _start=$(date +%s)
  DOCKER_CONFIG="$_BK_AUTH_DIR" buildctl --addr "$BUILDKIT_HOST" build \
    --frontend dockerfile.v0 \
    --local "context=${_ctx}" \
    --local "dockerfile=${_ctx}" \
    --opt "platform=${PUBLISH_PLATFORM}" \
    "${_opt_args[@]+"${_opt_args[@]}"}" \
    --output "$_out" || _rc=$?
  [ "$_rc" -eq 0 ] && echo "  ✓ $_tag → ${REGISTRY_HOST}/library/${_tag} ($(($(date +%s) - _start))s)" \
                   || echo "  ✗ $_tag — buildctl failed" >&2
  return "$_rc"
}

# Dispatch a single base build to the configured builder.
_build_base() {
  if [ "$BASE_BUILDER" = "buildkit" ]; then
    _build_base_buildkit "$1" "$2"
  else
    _build_base_quiet "$1" "$2"
  fi
}

build_base_images() {
  # Prebuilt: trust the registry already has the bases (no Docker daemon available,
  # e.g. a Docker-less host). The bases must have been seeded out-of-band (CI →
  # registry); buildkitd resolves `FROM pipeline-plugin-base:24.04` from there.
  if [ "$BASES_PREBUILT" = true ]; then
    echo "=== Base images: PREBUILT — trusting the in-cluster registry (skipping docker build + push) ==="
    return 0
  fi

  local _base_root="$PLUGINS_DIR/_base"
  [ ! -d "$_base_root" ] && return 0

  echo "=== Building base images ==="
  # Register QEMU/binfmt when PUBLISH_PLATFORM differs from the host arch, so a
  # cross-arch `docker build --platform` doesn't die with `exec format error`.
  # The local setup.sh scripts already do this, but the AWS/standalone build
  # paths did not — wire it in here so every path is covered. ensure-binfmt.sh
  # is idempotent + non-fatal (no-op on same-arch / Docker Desktop).
  if [ "${BASE_BUILDER:-docker}" = docker ] && [ "$DRY_RUN" != true ]; then
    bash "$SCRIPT_DIR/ensure-binfmt.sh" "$PUBLISH_PLATFORM" || true
  fi
  if [ "$DRY_RUN" = true ]; then
    echo "  (dry-run) skipping base builds"
    return 0
  fi

  # Root base must build first.
  if [ -f "$_base_root/_plugin-base/Dockerfile" ]; then
    _build_base "pipeline-plugin-base:24.04" "$_base_root/_plugin-base" || return 1
  fi

  # Family bases — alphabetical, all inherit FROM pipeline-plugin-base:24.04.
  # Skip `_plugin-base` itself: it matches the `_*-base` glob but is the
  # root base built above with the `:24.04` tag. Without this guard, the
  # loop builds the same Dockerfile a second time as `pipeline-plugin-
  # base:1.0`, wasting build time and publishing a stale duplicate tag.
  for _fam_dir in "$_base_root"/_*-base; do
    [ -d "$_fam_dir" ] || continue
    local _name
    _name=$(basename "$_fam_dir" | sed 's/^_//')
    [ "$_name" = "plugin-base" ] && continue
    _build_base "pipeline-${_name}:1.0" "$_fam_dir" || return 1
  done

  # buildkit mode pushed each base directly (--output push=true) — no separate push step.
  if [ "$BASE_BUILDER" = "buildkit" ]; then
    echo "  (buildkit) bases pushed to ${REGISTRY_HOST}/library/ during build."
    echo ""
    return 0
  fi

  # Push the bases into the in-cluster registry so buildkitd (separate
  # image cache from the host docker daemon) can resolve them. The
  # buildkitd.toml mirror at deploy/local/docker/config/buildkitd/ maps
  # docker.io → registry:5000, so bare `FROM pipeline-plugin-base:24.04`
  # in plugin Dockerfiles resolves via that mirror.
  #
  # Fail loudly if the push fails — a half-pushed registry leaves plugin
  # builds failing at runtime with a misleading `insufficient_scope`
  # error (registry returns the same response for missing-repo and
  # actual-scope-denied). Better to abort here so the operator sees the
  # real cause (network, auth, realm misconfig).
  # The push is MANDATORY, not best-effort: a missing/non-executable pusher used
  # to make this an `if [ -x … ]` no-op, so the bases were built and never
  # published and every later plugin build failed with the misleading
  # `insufficient_scope`. Invoke via `bash` so a lost exec bit (tarball copy,
  # restrictive umask) can't silently disable the step.
  if [ ! -f "$SCRIPT_DIR/push-base-images.sh" ]; then
    echo "ERROR: $SCRIPT_DIR/push-base-images.sh is missing — built bases cannot be published to ${REGISTRY_HOST}." >&2
    return 1
  fi
  # --force ⇒ re-push even when the tag already exists remotely, so a forced
  # rebuild actually replaces the registry copy. push-base-images.sh otherwise
  # skips any tag already present (its idempotency short-circuit), which made
  # `--force` rebuild-then-skip the push. An explicit FORCE_PUSH env still wins.
  FORCE_PUSH="${FORCE_PUSH:-$([ "$FORCE" = true ] && echo true || echo false)}" \
    bash "$SCRIPT_DIR/push-base-images.sh"
  echo ""
}

# Cumulative cleanup, installed BEFORE the first thing that creates a temp:
# _BK_AUTH_DIR holds a config.json with the in-cluster registry's `_token`
# credential (a live deploy-bootstrap JWT) and is created inside
# build_base_images, while PLUGIN_LIST_FILE is created further down. Installed
# at the plugin loop instead, the credential dir would survive every exit that
# happens first — `--bases-only` (which exits right after the base build) and
# any base-build failure.
_cleanup() {
  [ -n "${PLUGIN_LIST_FILE:-}" ] && rm -f "$PLUGIN_LIST_FILE"
  [ -n "${_BK_AUTH_DIR:-}" ] && rm -rf "$_BK_AUTH_DIR"
  return 0
}
trap _cleanup EXIT INT TERM

build_base_images

# Under --bases-only the caller (e.g. init-platform.sh under the
# build_image strategy) wants only the base images built + pushed —
# per-plugin image building is deferred to build-at-upload-time.
if [ "$BASES_ONLY" = true ]; then
  exit 0
fi

# ---- Build category list ----
#
# Skip directories whose name starts with `_` — these are infrastructure
# (currently `_base`), not plugins. Excluded from build, upload, and load.

# Both branches must yield a SPACE-separated list: the build loop matches with
# `case " $CATEGORIES " in *" $category "*`, which needs a space on each side.
# list_categories prints one per line, so the unfiltered (default) run matched
# NOTHING — every category hit the `continue` and the whole run built 0 images
# while reporting "Built: 0 / Failed: 0". `tr` collapses that to spaces.
if [ -n "$CATEGORY_FILTER" ]; then
  CATEGORIES=$(echo "$CATEGORY_FILTER" | tr ',' ' ')
else
  CATEGORIES=$(list_categories "$PLUGINS_DIR" | tr '\n' ' ')
fi

# ---- Reset mode ----

if [ "$RESET" = true ]; then
  echo "=== Resetting all plugins to build_image ==="
  count=0
  for category_dir in "$PLUGINS_DIR"/*/; do
    # `_*` dirs (e.g. `_base`) are infrastructure, not plugins — excluded from
    # the upload/load flow everywhere else (see the `! -name '_*'` filter note
    # above); skip them here too so reset never rewrites a base-image config.
    case "$(basename "$category_dir")" in _*) continue ;; esac
    for plugin_dir in "$category_dir"*/; do
      case "$(basename "$plugin_dir")" in _*) continue ;; esac
      config="$plugin_dir/config.yaml"
      [ -f "$config" ] || continue

      # An absent field yields "" (get_spec_field's contract), and every caller
      # here branches on empty — a missing field is normal, not a failure.
      _bt=$(get_spec_field buildType "$config")
      [ "$_bt" = "prebuilt" ] || continue

      # Revert config.yaml in one yq write, so field order is deterministic
      # across plugins.
      yq -i 'del(.imageTag) | .buildType = "build_image" | .dockerfile = "Dockerfile"' "$config"

      # Remove image.tar
      rm -f "$plugin_dir/image.tar"

      name=$(basename "$plugin_dir")
      category=$(basename "$category_dir")
      echo "  RESET ${category}/${name}"
      count=$((count + 1))
    done
  done
  echo ""
  echo "Reset $count plugin(s) to build_image."
  echo "Run 'load-plugins.sh --rebuild' to rebuild plugin.zip files."
  exit 0
fi

# ---- Main build loop ----

echo "=== Building Plugin Images ==="
echo "  Mode:       $([ "$FORCE" = true ] && echo "force" || echo "interactive")"
echo "  Dry-run:    $DRY_RUN"
echo "  Categories: ${CATEGORY_FILTER:-all}"
echo "  Max size:   ${MAX_IMAGE_SIZE_MB}MB"
echo ""

BUILT=0; SKIPPED=0; FAILED=0

# Build list of eligible plugin directories into a temp file (avoids subshell).
# The EXIT trap that removes it (and the buildkit auth dir) is already installed
# above build_base_images.
PLUGIN_LIST_FILE=$(mktemp)
for category_dir in "$PLUGINS_DIR"/*/; do
  category=$(basename "$category_dir")
  case " $CATEGORIES " in *" $category "*) ;; *) continue ;; esac
  for plugin_dir in "$category_dir"*/; do
    [ -f "$plugin_dir/plugin-spec.yaml" ] && [ -f "$plugin_dir/Dockerfile" ] && echo "$plugin_dir" >> "$PLUGIN_LIST_FILE"
  done
done
TOTAL=$(wc -l < "$PLUGIN_LIST_FILE" | tr -d ' ')

# An empty list is NOT a successful build of nothing — it means the plugins tree
# is missing or `--category` named something that does not exist. Falling through
# printed "Built: 0" and exited 0, which reads as a green build to init-platform.sh
# and CI while no image was produced.
if [ "$TOTAL" -eq 0 ]; then
  echo "ERROR: no buildable plugins found under $PLUGINS_DIR for categories: ${CATEGORY_FILTER:-all}" >&2
  echo "  A buildable plugin needs both plugin-spec.yaml and Dockerfile." >&2
  echo "  Known categories: $(list_categories "$PLUGINS_DIR" | tr '\n' ' ')" >&2
  exit 1
fi

CURRENT=0
# Feed the loop from fd 3, NOT stdin. Two things depended on stdin staying the
# terminal and both were broken while the list was piped in on fd 0:
#   - the "source changed, rebuild?" prompt below is guarded by `[ -t 0 ]`, which
#     is false when fd 0 is the list file — so the documented interactive mode
#     never actually prompted;
#   - any child that reads stdin (a `docker run -i`-wrapped yq, for instance)
#     swallowed the remaining plugin paths, ending the loop after one plugin
#     while the summary still reported the full TOTAL.
while IFS= read -r plugin_dir <&3; do
    [ -n "$plugin_dir" ] || continue
    category=$(basename "$(dirname "$plugin_dir")")

    CURRENT=$((CURRENT + 1))
    name=$(get_spec_field name "$plugin_dir/plugin-spec.yaml")
    if [ -z "$name" ]; then
      echo "  [${CURRENT}/${TOTAL}] FAIL ${category}/$(basename "$plugin_dir") (plugin-spec.yaml has no name:)"
      FAILED=$((FAILED + 1))
      continue
    fi
    label="${category}/${name}"
    tag=$(compute_image_tag "$plugin_dir")

    # Build-skip decision tree. The build tag lives inside config.yaml as
    # `imageTag:` — same file the platform parses on upload, so build
    # script and runtime share one source of truth.
    #
    # Source state we trust: `imageTag:` from config.yaml. Build output:
    # `image.tar`. Either can be missing independently — `--cleanup`
    # deletes image.tar, a `git clean` deletes neither (config.yaml is
    # checked in), an interrupted build leaves config.yaml untouched.
    #
    # Reasons we'd skip a build, in priority order:
    #   1. `imageTag` matches current source AND `image.tar` exists →
    #      everything is in sync, definitely skip.
    #   2. `imageTag` matches current source but `image.tar` is gone →
    #      source is unchanged but the cached tar was deleted (probably
    #      by --cleanup). Skip only if we know the image is already in
    #      the in-cluster registry (REGISTRY_CHECK=true); otherwise
    #      rebuild so the next load-plugins step has something to upload.
    #   3. `image.tar` exists but `imageTag` is missing or mismatched →
    #      can't verify freshness, treat as stale and prompt/rebuild.
    if [ "$FORCE" != true ]; then
      # An ABSENT `imageTag:` is the NORMAL case (a plugin that has never been
      # built, or one just reverted by --reset); it yields "" per
      # get_spec_field's contract and the decision tree above handles it.
      existing_tag=$(get_spec_field imageTag "$plugin_dir/config.yaml")
      hash_matches=$([ "$existing_tag" = "$tag" ] && echo true || echo false)
      tar_present=$([ -f "$plugin_dir/image.tar" ] && echo true || echo false)

      if [ "$hash_matches" = true ] && [ "$tar_present" = true ]; then
        echo "  [${CURRENT}/${TOTAL}] SKIP $label (image.tar exists, hash unchanged)"
        SKIPPED=$((SKIPPED + 1))
        continue
      fi
      if [ "$hash_matches" = true ] && [ "$tar_present" = false ] && [ "${REGISTRY_CHECK:-false}" = true ]; then
        # image.tar was likely deleted by --cleanup. Source is unchanged,
        # so the registry should still hold the previously-uploaded copy.
        echo "  [${CURRENT}/${TOTAL}] SKIP $label (image.tar missing, hash unchanged — trusting registry copy)"
        SKIPPED=$((SKIPPED + 1))
        continue
      fi
      if [ "$tar_present" = true ] && [ "$hash_matches" != true ]; then
        # Hash mismatch with an existing tar — source changed since the
        # last build.
        if [ -t 0 ] && [ "$DRY_RUN" != true ]; then
          printf '  [%s/%s] %s has existing image.tar but source changed. Rebuild? [Y/n]: ' "$CURRENT" "$TOTAL" "$label"
          read -r _answer
          if [ "$_answer" = "n" ] || [ "$_answer" = "N" ]; then
            echo "    Skipped (manual)"
            SKIPPED=$((SKIPPED + 1))
            continue
          fi
        fi
      elif [ "$tar_present" = false ] && [ "$hash_matches" = true ]; then
        # image.tar gone, imageTag still current — quiet feedback that
        # we're rebuilding to recreate the tarball.
        echo "  [${CURRENT}/${TOTAL}] REBUILD $label (image.tar missing; pass REGISTRY_CHECK=true to skip when the image is already in the in-cluster registry)"
      fi
    fi

    if [ "$DRY_RUN" = true ]; then
      echo "  [${CURRENT}/${TOTAL}] BUILD $label -> $tag (dry-run)"
      BUILT=$((BUILT + 1))
      continue
    fi

    echo "  [${CURRENT}/${TOTAL}] BUILD $label -> $tag"

    # Build image — with retry on transient network failures.
    #
    # Plugin Dockerfiles overwhelmingly use `apt-get update && apt-get install`
    # which has no built-in retry. When archive.ubuntu.com / launchpad / sury
    # mirrors flap (504s, connection timeouts), the build fails on a fully
    # transient error. Retry the whole `docker build` up to BUILD_MAX_ATTEMPTS
    # times when the failure log matches a known-transient pattern; surface
    # any other failure (compile error, missing package, etc.) immediately.
    # `--build-arg K=V` flags from the spec's buildArgs, one per line from
    # yq_buildargs, flattened so `$build_args` word-splits into docker's argv.
    build_args=$(yq_buildargs "$plugin_dir/plugin-spec.yaml" | tr '\n' ' ')
    build_log=$(mktemp)
    max_attempts=${BUILD_MAX_ATTEMPTS:-3}
    attempt=1
    build_ok=false
    while [ "$attempt" -le "$max_attempts" ]; do
      # shellcheck disable=SC2086
      if docker build --progress plain --platform "$PUBLISH_PLATFORM" $build_args \
          -t "plugin:${tag}" -f "$plugin_dir/Dockerfile" "$plugin_dir" > "$build_log" 2>&1; then
        build_ok=true
        break
      fi
      if _is_transient_failure "$build_log"; then
        backoff=$((attempt * 10))
        echo "    transient network failure on attempt $attempt/$max_attempts — sleeping ${backoff}s"
        sleep "$backoff"
        attempt=$((attempt + 1))
        continue
      fi
      # Real failure — break out and report.
      break
    done
    if [ "$build_ok" != "true" ]; then
      echo "    FAIL (docker build failed after $attempt attempt(s) — last 20 lines:)"
      tail -20 "$build_log" | sed 's/^/      /'
      rm -f "$build_log"
      FAILED=$((FAILED + 1))
      continue
    fi
    rm -f "$build_log"

    # Save to tar
    tar_path="$plugin_dir/image.tar"
    if ! docker save "plugin:${tag}" -o "$tar_path" 2>/dev/null; then
      echo "    FAIL (docker save failed)"
      rm -f "$tar_path"
      docker rmi "plugin:${tag}" > /dev/null 2>&1 || true
      FAILED=$((FAILED + 1))
      continue
    fi

    # Check size
    tar_size_mb=$(( $(wc -c < "$tar_path") / 1024 / 1024 ))
    if [ "$tar_size_mb" -gt "$MAX_IMAGE_SIZE_MB" ]; then
      echo "    SKIP (image ${tar_size_mb}MB exceeds ${MAX_IMAGE_SIZE_MB}MB limit)"
      rm -f "$tar_path"
      docker rmi "plugin:${tag}" > /dev/null 2>&1 || true
      SKIPPED=$((SKIPPED + 1))
      continue
    fi

    # Update config.yaml. Synthesize a minimal one if the plugin lacks it
    # (rare — but one outlier plugin shouldn't abort an otherwise-clean run).
    # The schema's `.strict()` parser accepts `imageTag` and rejects
    # unknown fields; drop any stale `imageTag` before re-writing.
    # Image identity is `<name>:<version>` from plugin-spec.yaml; the local
    # docker tag (`plugin:${tag}` saved into image.tar) is incidental and
    # gets re-tagged at push time by `loadAndPush`.
    config="$plugin_dir/config.yaml"
    if [ ! -f "$config" ]; then
      printf 'pluginSpec: plugin-spec.yaml\ndockerfile: Dockerfile\nbuildType: build_image\n' > "$config"
    fi
    # Single yq write (deterministic field order): switch to prebuilt, drop
    # the source-build fields the .strict() schema would otherwise reject,
    # persist the fresh tag.
    TAG="$tag" yq -i '
      del(.imageTag) | del(.dockerfile)
      | .buildType = "prebuilt"
      | .imageTag = strenv(TAG)
    ' "$config"

    # Cleanup docker image
    docker rmi "plugin:${tag}" > /dev/null 2>&1 || true

    echo "    OK (${tar_size_mb}MB)"
    BUILT=$((BUILT + 1))
done 3< "$PLUGIN_LIST_FILE"

echo ""
echo "=== Summary ==="
echo "  Built:   $BUILT"
echo "  Skipped: $SKIPPED"
echo "  Failed:  $FAILED"

[ "$FAILED" -gt 0 ] && exit 1
exit 0
