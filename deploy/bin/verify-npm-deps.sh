#!/usr/bin/env bash
set -euo pipefail

# Verify that every PUBLISHED @pipeline-builder/* package pins @pipeline-builder/*
# dependency versions that ACTUALLY resolve on the npm registry. The npm analog of
# verify-image-tags.sh — run in CI AFTER `pnpm publish` to catch the gap where a
# package is published with an internal dependency version that was never published
# (e.g. pipeline-manager pinning ai-core@<unpublished>, which 404s on install).
#
# Usage:
#   deploy/bin/verify-npm-deps.sh [pkg ...]    # default: the published libraries
#
# Exit codes — THE convention shared by every deploy/bin/verify-*.sh:
#   0  verified: everything checked passed
#   1  FAILED: a real verdict — something is missing, unsigned or unreachable
#   2  nothing to verify (no refs / no files). Non-zero on purpose: a gate must
#      not go green having checked nothing.
#   3  could not verify — an infra error, never a verdict: a missing tool, a bad
#      argument, or the registry/network answering 5xx / rate-limiting.
# Here: 1 = an internal dep version is unpublished; 2 = no package was verifiable;
# 3 = a missing tool, an unreadable services.txt or an unreachable registry.

SCOPE='@pipeline-builder'
REGISTRY='https://registry.npmjs.org'

# Hard-require the tools this script drives. Without this, a CI runner missing
# python3 (the JSON parser below) would exit non-zero mid-loop with a cryptic
# error — or worse, a shell that tolerates it could report "all resolved" having
# checked nothing (false green on a release gate). Fail fast and legibly.
for _t in curl python3; do
  command -v "$_t" >/dev/null 2>&1 || { echo "ERROR: '$_t' is required but not installed." >&2; exit 3; }
done

# npm CDN propagation can lag a few seconds after `pnpm publish`, so retry a
# "missing" lookup before declaring a version genuinely unpublished (avoids a
# false release failure on the publish→serve race). Existing versions return on
# the first try, so this only costs time when something actually looks missing.
ATTEMPTS=6
DELAY=10
resolve() {  # <name> <version> → 0 if the exact version resolves on npm
  local dep="$1" want="$2" i
  for ((i = 1; i <= ATTEMPTS; i++)); do
    curl -fsS -o /dev/null "${REGISTRY}/${SCOPE}/${dep}/${want}" 2>/dev/null && return 0
    [ "$i" -lt "$ATTEMPTS" ] && sleep "$DELAY"
  done
  return 1
}

LIBS=("$@")
if [ "${#LIBS[@]}" -eq 0 ]; then
  # The published libraries. services.txt is generated by projen into EVERY
  # deploy target (byte-identical — test/deploy-contracts holds them equal).
  # This gate is a release check, not a deployment: it runs for no particular
  # target, so it reads the docker target's copy, the same one the schema
  # suites read.
  _services="$(dirname "${BASH_SOURCE[0]}")/../local/docker/services.txt"
  [ -f "$_services" ] || { echo "ERROR: $_services not found — cannot determine the published libraries." >&2; exit 3; }
  while read -r _kind _name _dir; do
    if [ "$_kind" = library ]; then LIBS+=("$_name"); fi
  done < <(grep -v '^#' "$_services")
fi

# Verifying nothing is not a pass. An empty list means services.txt lost its
# `library` rows (or the caller passed none) — this gate would otherwise print
# "all resolve ✓" on a release having checked zero packages.
if [ "${#LIBS[@]}" -eq 0 ]; then
  echo "ERROR: no packages to verify — nothing was checked, so this is not a pass." >&2
  exit 2
fi

echo "Verifying internal npm deps of ${#LIBS[@]} published package(s) …"
MISSING=()
CHECKED=0
PACKUMENT="$(mktemp)"
trap 'rm -f "$PACKUMENT"' EXIT INT TERM
for lib in "${LIBS[@]}"; do
  # Fetch the packument WITH its HTTP status, so "never published" (404 — a
  # legitimate skip before a package's first release) is told apart from
  # "registry unreachable / unreadable" (an infra error). The single `|| true`
  # this replaces collapsed both into a warn+skip, so a flaky registry or a
  # broken parse could green this release gate having verified nothing.
  code="$(curl -sSL -o "$PACKUMENT" -w '%{http_code}' --max-time 30 \
    "${REGISTRY}/${SCOPE}/${lib}" 2>/dev/null || echo 000)"
  case "$code" in
    200) ;;
    404) echo "  warn  ${SCOPE}/${lib}: never published — skipping"; continue ;;
    *)   echo "ERROR: ${SCOPE}/${lib}: npm registry returned HTTP ${code} — cannot verify (infra error, not a verdict)." >&2
         exit 3 ;;
  esac

  # Latest published version + its @pipeline-builder deps, as `VERSION x` / `DEP name req` lines.
  if ! info="$(python3 -c "
import sys, json
d = json.load(sys.stdin)
v = d['dist-tags']['latest']
print('VERSION', v)
for k, req in d['versions'][v].get('dependencies', {}).items():
    if k.startswith('${SCOPE}/'):
        print('DEP', k.split('/', 1)[1], req)
" < "$PACKUMENT")"; then
    echo "ERROR: ${SCOPE}/${lib}: could not read dist-tags.latest from the registry metadata — cannot verify." >&2
    exit 3
  fi

  ver="$(awk '/^VERSION /{print $2; exit}' <<<"$info")"
  if [ -z "$ver" ]; then
    echo "ERROR: ${SCOPE}/${lib}: registry metadata has no latest version — cannot verify." >&2
    exit 3
  fi
  CHECKED=$((CHECKED + 1))
  echo "${SCOPE}/${lib}@${ver}:"
  while read -r tag dep req; do
    [ "$tag" = DEP ] || continue
    want="${req#^}"; want="${want#~}"          # internal deps are pinned exact; tolerate ^/~
    if resolve "$dep" "$want"; then
      echo "  ok      ${SCOPE}/${dep}@${req}"
    else
      echo "  MISSING ${SCOPE}/${dep}@${req}"
      MISSING+=("${SCOPE}/${lib}@${ver} → ${SCOPE}/${dep}@${req}")
    fi
  done <<<"$info"
done

# This gate runs AFTER `pnpm publish`, so at least one package must have been
# readable. All of them 404-ing means the publish never happened (or the scope
# is wrong) — not "everything resolves".
if [ "$CHECKED" -eq 0 ]; then
  echo "ERROR: none of the ${#LIBS[@]} package(s) are published on npm — nothing was verified." >&2
  exit 2
fi

if [ "${#MISSING[@]}" -gt 0 ]; then
  {
    echo
    echo "ERROR: ${#MISSING[@]} internal dependency version(s) are NOT published on npm:"
    printf '  - %s\n' "${MISSING[@]}"
    echo "Publish the missing version(s) — a published package must not pin an unpublished internal dep."
  } >&2
  exit 1
fi

echo
echo "All internal @pipeline-builder npm deps resolve ✓"
