import type { GrypePackageType, PackageFixChoice } from '@pipeline-builder/api-core';

/** The build context's text files (path relative to the context root → content). */
export type SourceTree = ReadonlyMap<string, string>;

/** A lockfile regeneration run in an isolated tool build (see tooling.ts). */
export interface ToolRun {
  ecosystem: 'npm' | 'go' | 'cargo' | 'bundler' | 'dotnet' | 'gradle';
  /** Directory (relative to the context root) the tool runs in. */
  dir: string;
  /** Shell command run there (built from validated names and versions only). */
  command: string;
  /** Files (relative to `dir`) copied back into the context afterwards. */
  outputs: string[];
}

/** One package's source patch. */
export interface SourcePatch {
  purl: string;
  packageType: GrypePackageType;
  /** The edited files (full new content). */
  files: Map<string, string>;
  /** Lockfiles to regenerate after the edit (their diff is not scope-checked). */
  regenerate: ToolRun[];
  /** Paths whose content is regenerated by `regenerate` (exempt from the line-scope check). */
  lockfiles: string[];
}

/** A source patcher: null when this package is not declared anywhere it can edit. */
export type SourcePatcher = (tree: SourceTree, target: FixTarget, ctx: PatchContext) => SourcePatch | null;

/** A package with a chosen fix version. */
export type FixTarget = PackageFixChoice & { fixVersion: string };

export interface PatchContext {
  /** The Dockerfile's path in the context (relative). */
  dockerfile: string;
}

/** Validated-name guard for anything interpolated into a shell command. */
export const SAFE_TOKEN = /^[A-Za-z0-9@][A-Za-z0-9@._+:~/-]{0,213}$/;
export const isSafeToken = (s: string): boolean => SAFE_TOKEN.test(s) && !s.includes('..');

/** Map helper: a copy of `tree` with `path` replaced. */
export function withFile(files: Map<string, string>, path: string, content: string): Map<string, string> {
  files.set(path, content);
  return files;
}

/** The directory part of a relative path ('' for the root). */
export const dirOf = (p: string): string => (p.includes('/') ? p.slice(0, p.lastIndexOf('/')) : '');
export const joinPath = (dir: string, name: string): string => (dir ? `${dir}/${name}` : name);
export const baseName = (p: string): string => p.split('/').pop() ?? p;

/** Parse a purl's namespace / name / version (`pkg:maven/g/a@v` → { namespace: 'g', name: 'a' }). */
export function parsePurl(purl: string): { type: string; namespace: string | null; name: string; version: string | null } | null {
  const m = /^pkg:([a-z0-9.+-]+)\/(.+?)(?:@([^?#]+))?(?:[?#].*)?$/i.exec(purl);
  if (!m) return null;
  const path = m[2]!.split('/').map((s) => decodeURIComponent(s));
  const name = path.pop()!;
  return { type: m[1]!.toLowerCase(), namespace: path.length > 0 ? path.join('/') : null, name, version: m[3] ? decodeURIComponent(m[3]) : null };
}

export const escapeRe = (s: string): string => s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
